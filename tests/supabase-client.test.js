const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const calls=[];
const context={window:{},fetch:async(url,options)=>{calls.push({url,options});return {ok:true,json:async()=>[{id:'example'}]}}};
vm.runInNewContext(fs.readFileSync('core/supabase-client.js','utf8'),context);
const agency='11111111-1111-4111-8111-111111111111';
const incident='22222222-2222-4222-8222-222222222222';
const unit='33333333-3333-4333-8333-333333333333';
(async()=>{
 assert.throws(()=>context.window.CadSupabase.create({url:'http://insecure.test',anonKey:'pub',getAccessToken:()=> 'token'}),/HTTPS/);
 const client=context.window.CadSupabase.create({url:'https://cad-test.supabase.co',anonKey:'publishable-key',getAccessToken:async()=> 'user-jwt'});
 await client.listOutstanding(agency);
 assert.match(calls[0].url,/cad_outstanding_resources\?agency_id=eq\./);
 assert.equal(calls[0].options.headers.Authorization,'Bearer user-jwt');
 assert.equal(calls[0].options.cache,'no-store');
 await client.assignResponsePlan({agency,incident,unitIds:[unit],incidentVersion:2,unitVersions:{[unit]:0}});
 assert.match(calls[1].url,/rpc\/cad_assign_response_plan$/);
 assert.equal(JSON.parse(calls[1].options.body).p_expected_incident_version,2);
 assert.equal(JSON.parse(calls[1].options.body).p_unit_ids[0],unit);
 assert.equal(calls[1].options.method,'POST');
 await client.setRequirements({agency,incident,incidentVersion:3,requirements:[{resource_type:'ENGINE',count:3}]});
 assert.match(calls[2].url,/rpc\/cad_set_response_requirements$/);
 assert.equal(JSON.parse(calls[2].options.body).p_requirements[0].count,3);
 await client.listIncidentEvents(agency);
 assert.match(calls.at(-1).url,/cad_incident_events\?agency_id=eq\./);
 await client.listIncidentLocations(agency);
 assert.match(calls.at(-1).url,/cad_incident_locations\?agency_id=eq\./);
 await client.setCaseNumber({agency,incident,caseNumber:'2026-001',incidentVersion:3});
 assert.match(calls.at(-1).url,/rpc\/cad_set_case_number$/);
 await client.addNarrative({agency,incident,text:'Demo narrative',incidentVersion:4});
 assert.match(calls.at(-1).url,/rpc\/cad_add_narrative$/);
 assert.equal(JSON.parse(calls.at(-1).options.body).p_text,'Demo narrative');
 await client.correctLocation({agency,incident,location:'123 Demo St',incidentVersion:5});
 assert.match(calls.at(-1).url,/rpc\/cad_correct_location$/);
 await client.closeIncident({agency,incident,disposition:'Handled',incidentVersion:6});
 assert.match(calls.at(-1).url,/rpc\/cad_close_incident$/);
 const unauth=context.window.CadSupabase.create({url:'https://cad-test.supabase.co',anonKey:'pub',getAccessToken:()=>null});
 await assert.rejects(unauth.listUnits(agency),/login required/);
 assert.throws(()=>client.listUnits('not-a-uuid'),/UUID/);
 console.log('Supabase client tests passed');
})().catch(e=>{console.error(e);process.exitCode=1});
