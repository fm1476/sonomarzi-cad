const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const repo=path.join(__dirname,'..');
const events=[];
const state={incidents:[{id:'26-004521',type:'Fire Alarm',discipline:'FIRE',status:'ACTIVE',units:['E1'],location:'123 Main Street',events:[]}]};
const ctx={state,config:{types:{FIRE:['Fire Alarm','Structure Fire']}},window:{},event:(i,e)=>events.push([i.id,e])};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(repo,'incident-intelligence.js'),'utf8'),ctx);
const parsed=ctx.window.cadIncidentIntelligence.classification('E1 on scene at the alarm, confirmed working structure fire');
assert.equal(parsed.type,'Structure Fire');
assert.equal(parsed.discipline,'FIRE');
assert.equal(ctx.window.cadIncidentIntelligence.resolveIncident('E1 reports working fire',['E1']).id,'26-004521');
assert.equal(ctx.window.cadIncidentIntelligence.classification('E1 reports possible structure fire').review,'Classification not confirmed');
const voice=fs.readFileSync(path.join(repo,'voice.js'),'utf8');
const helper=voice.slice(voice.indexOf('async function processSharedVoiceReclassification('),voice.indexOf('async function processSharedVoiceStatus('));
assert(helper.includes("window.cadSharedCommand('reclassify'"));
assert(helper.includes("window.cadSharedCommand('status'"));
assert(helper.includes("latest.type!==parsed.type"));
assert(helper.includes("latest.units||[]"));
assert(!helper.includes('save()'),'shared CFS must not use local-only persistence');
const shared=fs.readFileSync(path.join(repo,'core/shared-demo-panel.js'),'utf8');
assert(shared.includes("client.reclassifyIncident("));
const api=fs.readFileSync(path.join(repo,'core/supabase-client.js'),'utf8');
assert(api.includes("rpc('cad_reclassify_incident'"));
console.log('PASS: working fire voice reclassification uses authenticated shared CFS RPC and preserves incident identity');
