const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const context={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../core/unit-commands.js'),'utf8'),context);
const assign=context.window.CadUnitCommands.assign;
const incident={id:'I1',agency:'Fire',status:'PENDING',location:'100 Main',units:[],events:[]};
const other={id:'I2',agency:'Fire',status:'ACTIVE',location:'200 Main',units:['E2'],events:[]};
const state={incidents:[incident,other]};
const e1={id:'E1',status:'AVAILABLE',location:'Station'},e3={id:'E3',status:'AVAILABLE',location:'Station'};
const event=(i,msg)=>i.events.push(msg);
const call=(unit,sharedGroups=[])=>assign({state,incident,unit,event,sharedGroups});
assert.equal(call(e1,[{agency:'Fire',units:['E1','E2']}]).ok,false);
assert.equal(e1.status,'AVAILABLE');
assert.equal(incident.units.length,0);
assert.equal(call(e3).ok,true);
assert.equal(e3.status,'DISPATCHED');
assert.equal(incident.status,'ACTIVE');
assert.equal(incident.units[0],'E3');
assert.equal(call(e3).ok,false);
assert.equal(incident.units.length,1);
assert.ok(incident.events.some(x=>x.includes('UNIT_ASSIGNED E3')));
const busy={id:'E2',status:'AVAILABLE'};
assert.equal(call(busy).ok,false);
assert.equal(busy.status,'AVAILABLE');
console.log('Unit assignment command regression checks passed');

const plan={id:'P1',agency:'Fire',status:'PENDING',location:'300 Main',units:[],events:[]};
state.incidents.push(plan);
const e4={id:'E4',status:'AVAILABLE',location:'Station'};
const e5={id:'E5',status:'AVAILABLE',location:'Station'};
state.units=[e4,e5];
const planCall=(ids,groups=[])=>context.window.CadUnitCommands.assignPlan({state,incident:plan,unitIds:ids,event,sharedGroups:groups});
assert.equal(planCall(['E4','E5'],[{agency:'Fire',units:['E4','E5']}]).ok,false);
assert.equal(plan.units.length,0);
assert.equal(e4.status,'AVAILABLE');
assert.equal(planCall(['E4','E5']).ok,true);
assert.equal(plan.units.length,2);
const clear=context.window.CadUnitCommands.clear;
const cleared=clear({incident:plan,unit:e4,disposition:'',source:'TEST',event,now:()=> '12:00'});
assert.equal(cleared.ok,true);
assert.equal(plan.status,'ACTIVE');
assert.equal(plan.units.length,1);
assert.equal(e4.status,'CLEAR');
assert.equal(clear({incident:plan,unit:e4,event,now:()=> '12:01'}).ok,false);

const setStatus=context.window.CadUnitCommands.setStatus;
assert.equal(setStatus({state,unit:e5,status:'AVAILABLE',event}).ok,false);
assert.equal(setStatus({state,unit:e5,status:'ENROUTE',incident:plan,event}).ok,true);
assert.equal(e5.status,'ENROUTE');
const closure=context.window.CadUnitCommands.closeEvent;
assert.equal(closure({state,incident:plan,disposition:'',event,now:()=> '13:00'}).ok,false);
assert.equal(plan.status,'ACTIVE');
assert.equal(closure({state,incident:plan,disposition:'False alarm',event,now:()=> '13:01'}).ok,true);
assert.equal(plan.status,'CLOSED');
assert.equal(e5.status,'AVAILABLE');
assert.equal(plan.units.length,0);
assert.equal(closure({state,incident:plan,disposition:'Duplicate',event,now:()=> '13:02'}).ok,false);
