const assert=require('node:assert/strict'),fs=require('node:fs');
const {activate,logOff}=require('../core/unit-activation.js');
const master={agencies:[{id:'PD',name:'Petaluma Police',model:'HYBRID'}],units:[{id:'u',agencyId:'PD',designator:'3A14',discipline:'LAW',model:'FIXED'}]};
const roster=activate(master,{incidents:[],units:[]},'u');
const staffed={...roster,units:roster.units.map(u=>({...u,staffing:{active:true,personIds:['p']}}))};
assert.equal(logOff(staffed,'3A14').units.length,0,'available staffed officer may end shift');
assert.equal(master.units.length,1,'master definition retained');
assert.throws(()=>logOff({...roster,units:[{...roster.units[0],status:'ENROUTE'}]},'3A14'),/available or out of service/);
assert.throws(()=>logOff({...roster,incidents:[{id:'c',status:'ACTIVE',units:['3A14']}]},'3A14'),/assigned to an open incident/);
const board=fs.readFileSync('board-layout.js','utf8'),app=fs.readFileSync('app.js','utf8'),panel=fs.readFileSync('core/shared-demo-panel.js','utf8'),client=fs.readFileSync('core/supabase-client.js','utf8'),migration=fs.readFileSync('migrations/20261015_unit_duty.sql','utf8');
assert(board.includes("off.textContent='Off Duty'"));
assert(board.includes("['AVAILABLE','CLEAR'].includes(u.status) && !assigned.length"));
assert(board.includes('window.cadSharedSetUnitDuty?.(u.id,false)'));
assert(app.includes(".filter(u=>u.status!=='OFF_DUTY').map(u=>"));
assert(panel.includes("window.cadSharedSetUnitDuty=async function(unitId,onDuty)"));
assert(panel.includes("logOn.textContent='Log On Duty'"));
assert(client.includes("rpc('cad_set_unit_duty'"));
assert(migration.includes('v_u.status<>\'AVAILABLE\''),'only available shared units can go off duty');
assert(migration.includes('cleared_at is null'),'must clear assignments before off duty');
assert(migration.includes('cad_unit_duty_events'),'audit duty changes');
console.log('PASS: local and shared duty handling, guarded context action, and on-duty return');
