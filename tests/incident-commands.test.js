const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const context={window:{}};
vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname,'../core/incident-commands.js'),'utf8'),context);
const command=context.window.CadIncidentCommands.updateFields;
const state={incidents:[{id:'I1',status:'ACTIVE',type:'Alarm',priority:'P2',discipline:'FIRE',agency:'Fire',events:[],narrative:[]}]};
let saves=0;
const event=(i,message)=>i.events.push(message),save=()=>saves++;
const run=(updates,id='I1')=>command({state,id,updates,source:'TEST',event,save});
assert.equal(run({priority:'P8'}).ok,false);
assert.equal(saves,0);
assert.equal(state.incidents[0].priority,'P2');
assert.equal(run({discipline:'OTHER'}).ok,false);
assert.equal(saves,0);
assert.equal(run({priority:'P1',narrative:'Smoke showing'}).ok,true);
assert.equal(state.incidents[0].priority,'P1');
assert.equal(state.incidents[0].narrative[0],'Smoke showing');
assert.ok(state.incidents[0].events.some(e=>e.includes('FIELD_CHANGED PRIORITY')));
assert.equal(saves,1);
assert.equal(run({caller:'Test Caller'},'missing').ok,false);
state.incidents[0].status='CLOSED';
assert.equal(run({priority:'P2'}).ok,false);
assert.equal(saves,1);
console.log('Incident command regression checks passed');
