const assert=require('node:assert/strict'),fs=require('node:fs');
const loader=require('../sample-calls.js');
const html=fs.readFileSync('index.html','utf8');
const app=fs.readFileSync('app.js','utf8');
const samples=loader.catalog;
assert.equal(samples.length,6);
assert.equal(samples.filter(x=>x.discipline==='FIRE'&&x.type==='Fire Alarm').length,1);
assert.equal(samples.filter(x=>x.discipline==='EMS'&&x.type==='Medical Aid').length,1);
assert.equal(samples.filter(x=>x.discipline==='LAW').length,4);
assert(samples.every(x=>x.location.endsWith('Petaluma, CA')));
assert.equal(loader.selectMissing([]).length,6);
assert.equal(loader.selectMissing([{...samples[0],status:'PENDING'}]).length,5);
assert.equal(loader.selectMissing([{...samples[0],status:'CLOSED'}]).length,6);
assert(!html.includes('id="simulateBtn"'));
assert(!html.includes('Hackathon Scenario Controls'));
assert(!html.includes('id="reset"'));
assert(!html.includes('id="saveDemoPoint"'));
assert(!html.includes('demo-tools.js'));
assert(html.includes('id="cadLoadSampleCalls"'));
assert(html.includes('sample-calls.js?v=1'));
assert(!app.includes("$('#simulateBtn').onclick"));
assert(!app.includes("$('#reset').onclick"));
assert(app.includes('window.cadAddLocalSampleCalls=function(items)'));
assert(app.includes("if(cadSharedWorkspaceMode)throw Error("));
assert(loader.selectMissing(samples.map(x=>({...x,status:'PENDING'}))).length===0);
console.log('PASS: obsolete hackathon controls removed; 6 sample calls add non-destructively');
