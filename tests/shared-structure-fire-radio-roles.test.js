const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const intents=require('../core/shared-voice-intents.js');
const voiceText=require('../core/voice-text.js');
const roster=['E1','E2','E3','B1'].map(id=>({id}));
const radio='Engine One I copy you on scene with a working structure fire, requesting balance of assignment. Engine Two, Engine Three, Battalion One, respond structure fire, 450 East Washington Street.';
const parsed=intents.parseWorkingFireTransmission(radio,roster,voiceText);
assert.equal(parsed.reporter?.id,'E1','Engine One must be the reporter, not one of the responding units');
assert.deepEqual(parsed.responders.map(u=>u.id),['E2','E3','B1'],'explicit responding units only');
assert.match(parsed.report,/requesting balance of assignment/i);
assert.match(parsed.order,/450 East Washington Street/i);
assert.equal(parsed.reason,null);
const missing=intents.parseWorkingFireTransmission(radio,roster.filter(u=>u.id!=='E1'),voiceText);
assert.equal(missing.reporter,null,'never infer the reporting unit from responding apparatus');
assert.match(missing.reason,/not logged on/);
assert.equal(intents.parseWorkingFireTransmission('Engine Two respond to 450 East Washington',roster,voiceText),null);
const voice=fs.readFileSync('voice.js','utf8');
const start=voice.indexOf('function sharedRadioSegments(text){');
const end=voice.indexOf('async function processSharedVoiceCompound(',start);
assert(start>=0&&end>start);
const ctx={window:{CadSharedVoiceIntents:intents,CadVoiceText:voiceText},state:{units:roster}};
vm.createContext(ctx);
vm.runInContext(voice.slice(start,end),ctx);
assert.deepEqual(Array.from(ctx.sharedRadioSegments(radio)),[parsed.report,parsed.order]);
assert(voice.includes('const candidates=structured?[structured.reporter].filter(Boolean)'),'single reporting unit must be isolated for reclassification');
assert(voice.includes('structured?[structured.reporter].filter(Boolean)'),'compound order must use same reporting unit resolver');
console.log('PASS: compound fire radio separates reporter, scene report, and ordered response without guessing');